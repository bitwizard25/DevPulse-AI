"""Dependency contracts for the application layer."""

import builtins
from pathlib import Path
from typing import Protocol

from ..domain.jobs import Job, ReviewSnapshot
from ..domain.memory import IndexReport, MemoryChunk
from ..domain.models import Config, ProviderConfig
from ..domain.privacy import Vault


class StateStore(Protocol):
    def identity(self, value: str) -> str: ...
    def start(self, project: str, digest: str) -> str: ...
    def finish(self, session: str, result: dict | None = None, error: str | None = None): ...
    def cache_get(self, key: str) -> dict | None: ...
    def cache_put(self, key: str, result: dict, ttl: float = 86400): ...


class SourceReader(Protocol):
    def __call__(self, root: Path, *, file: str | None = None, worktree: bool = False) -> dict: ...


class ContextReader(Protocol):
    def __call__(self, root: Path, vault: Vault, budget: int = 24000, query: str = '') -> dict: ...


class ModelTransport(Protocol):
    def __call__(self, config: ProviderConfig, prompt: str) -> dict: ...


class CredentialReader(Protocol):
    def __call__(self, config: Config) -> list[str]: ...


class Clock(Protocol):
    def now(self) -> float: ...
    def monotonic(self) -> float: ...
    def sleep(self, seconds: float): ...


class CancellationToken(Protocol):
    def cancelled(self) -> bool: ...


class CircuitStore(Protocol):
    def read(self, key: str) -> tuple[int, float]: ...
    def write(self, key: str, failures: int, opened_until: float): ...


class JobStore(Protocol):
    def submit(self, snapshot: ReviewSnapshot, *, ttl: float = 86400) -> Job: ...
    def claim(self, owner: str) -> Job | None: ...
    def get(self, job_id: str) -> Job: ...
    def list(self, project: str | None = None, limit: int = 20) -> builtins.list[Job]: ...
    def heartbeat(self, job_id: str, owner: str) -> bool: ...
    def cancelled(self, job_id: str, owner: str) -> bool: ...
    def complete(self, job_id: str, owner: str, result: dict) -> bool: ...
    def fail(self, job_id: str, owner: str, error: str, *, retry_delay: float | None = None): ...
    def recover(self, owner: str): ...
    def expire(self): ...
    def cancel(self, job_id: str) -> Job: ...
    def retry(self, job_id: str) -> Job: ...


class MemoryIndex(Protocol):
    def refresh(self, root: Path, vault: Vault) -> IndexReport: ...
    def search(
        self, project: str, query: str, *, kind: str | None = None, limit: int = 8
    ) -> list[MemoryChunk]: ...
    def first_memory(self, project: str, limit: int = 8) -> list[MemoryChunk]: ...


class TokenCounter(Protocol):
    name: str
    exact: bool

    def count(self, text: str) -> int: ...
